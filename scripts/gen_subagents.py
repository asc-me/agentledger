def extract_section(md: str, heading: str) -> str:
    """Return the body under a `## <heading>...` up to the next `## `, trimmed."""
    out: list[str] = []
    capturing = False
    for line in md.splitlines():
        if line.startswith("## "):
            if capturing:
                break
            capturing = line[3:].strip().lower().startswith(heading.lower())
            continue
        if capturing:
            out.append(line)
    while out and not out[0].strip():
        out.pop(0)
    while out and not out[-1].strip():
        out.pop()
    return "\n".join(out)


def frontmatter(fm: dict) -> str:
    lines = ["---"]
    for key in ("name", "description", "model", "readonly", "is_background"):
        val = fm[key]
        if isinstance(val, bool):
            val = "true" if val else "false"
        lines.append(f"{key}: {val}")
    lines.append("---")
    return "\n".join(lines)


