def render_files() -> dict[str, str]:
    """Return {relative_path: content} for every generated file, all toolchains."""
    invariants = extract_section(AGENTS_MD.read_text(), "Invariants")
    if not invariants:
        raise SystemExit("could not extract '## Invariants' from AGENTS.md")

    per_dir: dict[str, str] = {"README.md": render_readme(invariants)}
    for role in ROSTER:
        fm = frontmatter(role)
        per_dir[f"{role['name']}.md"] = f"{fm}\n\n{role['body']}\n"

    files: dict[str, str] = {}
    for tool in TOOLCHAINS:
        for name, content in per_dir.items():
            files[f".{tool}/agents/{name}"] = content
    return files


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true", help="verify only; exit 1 if stale")
    args = ap.parse_args()

    files = render_files()
    if args.check:
        stale = []
        for rel, content in files.items():
            path = REPO / rel
            if not path.exists() or path.read_text() != content:
                stale.append(rel)
        if stale:
            print("Sub-agent fleet is stale — run `python scripts/gen_subagents.py`:")
            for rel in sorted(stale):
                print(f"  - {rel}")
            return 1
        print(f"Sub-agent fleet up to date ({len(files)} files across {len(TOOLCHAINS)} toolchains).")
        return 0

    for rel, content in files.items():
        path = REPO / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content)
    print(f"Wrote {len(files)} files across {len(TOOLCHAINS)} toolchains.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
